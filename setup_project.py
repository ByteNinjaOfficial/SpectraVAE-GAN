"""
GAN-VAE Project Structure Setup Script
Automatically creates the directory hierarchy under GAN/ for Phase 1 (EDA) through downstream GAN/VAE/CNN phases.
"""

from pathlib import Path

# Define root project directory and GAN subfolder
BASE_DIR = Path(__file__).resolve().parent
GAN_DIR = BASE_DIR / "GAN"

# Define directory structure under GAN/
DIRECTORIES = [
    GAN_DIR / "data" / "rvf10k",
    GAN_DIR / "notebooks",
    GAN_DIR / "src",
    GAN_DIR / "outputs" / "figures",
    GAN_DIR / "outputs" / "reports",
]

DIRECTORY_EXPLANATIONS = {
    "GAN/data/rvf10k": "Stores the raw, immutable RVF10K benchmark dataset (real and fake faces). Keeping raw data isolated ensures clean data provenance and prevents accidental in-place mutations.",
    "GAN/notebooks": "Contains Jupyter notebooks for exploratory data analysis, hypothesis testing, and narrative research documentation in CVPR/ICCV style.",
    "GAN/src": "Contains reusable, modular, and testable Python source code (integrity verification, photometric metrics, visualization utilities, config). Prevents notebook code bloat.",
    "GAN/outputs/figures": "Dedicated directory for high-DPI publication-grade plots, charts, and inspection grids generated by the analysis.",
    "GAN/outputs/reports": "Stores structured textual and tabular reports (e.g. data integrity summaries, statistical findings) for reproducibility and documentation.",
}

def create_project_structure():
    print(f"Initializing GAN project structure under: {GAN_DIR}\n")
    for directory in DIRECTORIES:
        directory.mkdir(parents=True, exist_ok=True)
        rel_path = directory.relative_to(BASE_DIR)
        print(f"  [CREATED] {rel_path}")

    print("\nDirectory Purpose & Rationale:")
    for path_str, explanation in DIRECTORY_EXPLANATIONS.items():
        print(f"  - {path_str:<22}: {explanation}")

    print("\nProject structure initialization complete.")

if __name__ == "__main__":
    create_project_structure()
